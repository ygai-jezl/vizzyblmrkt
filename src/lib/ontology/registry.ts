/** The type with this id, or undefined. */
export function typeById(id: string): OntologyType | undefined {
  return ONTOLOGY.find((t) => t.id === id);
}

/** Every store of every type, with the type it belongs to. */
export function storesOf(types: readonly OntologyType[] = ONTOLOGY): Array<StoreRef & { typeId: string }> {
  return types.flatMap((t) => t.stores.map((s) => ({ ...s, typeId: t.id })));
}
