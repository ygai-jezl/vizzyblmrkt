  (["us", "eu", "asia"] as const).map((region) => ({
    collection: table,
    db: "bigquery" as const,
    definedIn: `extensions/fsbq-${table === "email_events" ? "email-events" : "signups"}-${region}.env`,
    note: `dataset waitlist_${region}, mirrored from Firestore by the firestore-bigquery-export extension`,
  }));

